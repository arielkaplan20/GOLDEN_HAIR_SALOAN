// פסקת טקסט רגילה בעברית
function p(text, opts = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { after: opts.after === undefined ? 120 : opts.after, line: 300 },
    indent: opts.indent ? { start: opts.indent } : undefined,
    children: [
      new TextRun({
        text,
        font: FONT,
        size: opts.size || 24,
        bold: opts.bold || false,
        italics: opts.italics || false,
        color: opts.color || "000000",
        rightToLeft: true,
      }),
    ],
  });
}

// פסקה עם קטעי טקסט מעורבים (למשל עברית + מונח באנגלית)
function pMixed(parts, opts = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { after: opts.after === undefined ? 120 : opts.after, line: 300 },
    children: parts.map(
      (part) =>
        new TextRun({
          text: part.t,
          font: part.mono ? "Consolas" : FONT,
          size: part.size || opts.size || 24,
          bold: part.b || false,
          italics: part.i || false,
          color: part.color || "000000",
          rightToLeft: !part.ltr,
        })
    ),
  });
}

// כותרת ראשית - פרק
function h1(text) {
  return new Paragraph({
    bidirectional: true,
    heading: HeadingLevel.HEADING_1,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 360, after: 200 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 12, color: GOLD, space: 6 } },
    children: [new TextRun({ text, font: FONT, size: 34, bold: true, color: DARK, rightToLeft: true })],
  });
}

// כותרת משנה
function h2(text) {
  return new Paragraph({
    bidirectional: true,
    heading: HeadingLevel.HEADING_2,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 280, after: 140 },
    children: [new TextRun({ text, font: FONT, size: 28, bold: true, color: DARK, rightToLeft: true })],
  });
}

// כותרת רמה שלישית
function h3(text) {
  return new Paragraph({
    bidirectional: true,
    heading: HeadingLevel.HEADING_3,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 200, after: 100 },
    children: [new TextRun({ text, font: FONT, size: 25, bold: true, color: "000000", rightToLeft: true })],
  });
}

// שורת רשימה עם תבליט
function bullet(text, level = 0) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    bullet: { level },
    spacing: { after: 80, line: 300 },
    children: [new TextRun({ text, font: FONT, size: 24, rightToLeft: true })],
  });
}

// שורת רשימה ממוספרת ידנית (כדי לשלוט במספור המדויק)
function numbered(num, text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.JUSTIFIED,
    spacing: { after: 80, line: 300 },
    indent: { start: 360, hanging: 260 },
    children: [
      new TextRun({ text: num + ". ", font: FONT, size: 24, bold: true, rightToLeft: true }),
      new TextRun({ text, font: FONT, size: 24, rightToLeft: true }),
    ],
  });
}

// בלוק קוד / פסאודו-קוד - שמאל לימין, גופן ברוחב קבוע
function code(lines) {
  return lines.map(
    (line) =>
      new Paragraph({
        bidirectional: false,
        alignment: AlignmentType.LEFT,
        spacing: { after: 0, line: 260 },
        shading: { type: ShadingType.CLEAR, fill: GREY },
        indent: { left: 200, right: 200 },
        children: [new TextRun({ text: line || " ", font: "Consolas", size: 19 })],
      })
  );
}

// תא בטבלה
function cell(text, opts = {}) {
  const content = Array.isArray(text) ? text : [text];
  return new TableCell({
    width: opts.width ? { size: opts.width, type: WidthType.PERCENTAGE } : undefined,
    shading: opts.head
      ? { type: ShadingType.CLEAR, fill: DARK }
      : opts.fill
      ? { type: ShadingType.CLEAR, fill: opts.fill }
      : undefined,
    margins: { top: 60, bottom: 60, left: 80, right: 80 },
    children: content.map(
      (t) =>
        new Paragraph({
          bidirectional: true,
          alignment: opts.align || (opts.head ? AlignmentType.CENTER : AlignmentType.RIGHT),
          spacing: { after: 0, line: 260 },
          children: [
            new TextRun({
              text: String(t),
              font: opts.mono ? "Consolas" : FONT,
              size: opts.size || 21,
              bold: opts.head || opts.bold || false,
              color: opts.head ? "FFFFFF" : opts.color || "000000",
              rightToLeft: !opts.mono,
            }),
          ],
        })
    ),
  });
}

// טבלה שלמה. headers = מערך כותרות, rows = מערך של מערכי תאים
function table(headers, rows, widths) {
  const border = { style: BorderStyle.SINGLE, size: 4, color: "AAAAAA" };
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    visuallyRightToLeft: true,
    borders: { top: border, bottom: border, left: border, right: border,
               insideHorizontal: border, insideVertical: border },
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((h, i) => cell(h, { head: true, width: widths && widths[i] })),
      }),
      ...rows.map(
        (r, ri) =>
          new TableRow({
            children: r.map((c, i) =>
              cell(c, { width: widths && widths[i], fill: ri % 2 ? GREY : undefined })
            ),
          })
      ),
    ],
  });
}

// תיבת הערה מודגשת
function note(title, text) {
  const border = { style: BorderStyle.SINGLE, size: 4, color: GOLD };
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    visuallyRightToLeft: true,
    borders: { top: border, bottom: border, left: border, right: border,
               insideHorizontal: border, insideVertical: border },
    rows: [
      new TableRow({
        children: [
          new TableCell({
            shading: { type: ShadingType.CLEAR, fill: "FFF8E7" },
            margins: { top: 120, bottom: 120, left: 140, right: 140 },
            children: [
              new Paragraph({
                bidirectional: true, alignment: AlignmentType.RIGHT, spacing: { after: 60 },
                children: [new TextRun({ text: title, font: FONT, size: 23, bold: true, color: "8B6508", rightToLeft: true })],
              }),
              new Paragraph({
                bidirectional: true, alignment: AlignmentType.JUSTIFIED, spacing: { after: 0, line: 280 },
                children: [new TextRun({ text, font: FONT, size: 22, rightToLeft: true })],
              }),
            ],
          }),
        ],
      }),
    ],
  });
}

// תרשים PlantUML - כותרת, הסבר וקוד המקור
function diagram(title, description, umlLines) {
  return [
    h3(title),
    p(description),
    p("קוד המקור לתרשים (PlantUML):", { bold: true, after: 60, size: 22 }),
    ...code(umlLines),
    p("", { after: 200 }),
  ];
}

function spacer(h = 200) {
  return new Paragraph({ spacing: { after: h }, children: [] });
}

function pageBreak() {
  return new Paragraph({ children: [new PageBreak()] });
}

// שורת חתימה - קו לחתימה ידנית
function signatureLine(label) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 400, after: 100 },
    children: [
      new TextRun({ text: label + ": ", font: FONT, size: 24, bold: true, rightToLeft: true }),
      new TextRun({ text: "________________________", font: FONT, size: 24, rightToLeft: true }),
    ],
  });
}

