const SEQ_STYLE = [
  "@startuml",
  "hide footbox",
  "skinparam backgroundColor white",
  "skinparam defaultFontName Arial",
  "skinparam defaultFontSize 13",
  "skinparam sequence {",
  "  ArrowColor black",
  "  ArrowFontColor black",
  "  ActorBorderColor black",
  "  ActorBackgroundColor #66CCFF",
  "  LifeLineBorderColor black",
  "  LifeLineBackgroundColor #99DDFF",
  "  ParticipantBorderColor black",
  "  ParticipantBackgroundColor #66CCFF",
  "  ParticipantFontColor black",
  "  ParticipantFontSize 13",
  "  GroupBorderColor black",
  "  GroupBackgroundColor white",
  "  GroupHeaderFontColor black",
  "}",
  "",
];

// מרכיב תרשים שלם: העיצוב הקבוע + גוף התרשים + סיום
function seqDiagram(title, description, body) {
  return H.diagram(title, description, SEQ_STYLE.concat(body).concat(["@enduml"]));
}


